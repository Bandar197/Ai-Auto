metadata = MetaData(schema="automind")

TS = DateTime(timezone=True)


def _id() -> Column:
    # Default (gen_random_uuid()) lives in the migration; FetchedValue tells SQLAlchemy so.
    return Column("id", UUID(as_uuid=True), primary_key=True, server_default=FetchedValue())


def _uuid(name: str, **kw) -> Column:
    return Column(name, UUID(as_uuid=True), **kw)


