"""SQLAlchemy Core tables mirroring ``supabase/migrations`` (schema ``automind``).

The SQL migrations are the single source of truth; these definitions only
describe columns for query building and type coercion (no DDL is ever
emitted from here). Server-side defaults are therefore not repeated: omit a
column on insert and the database default applies.
"""

