def build() -> dict:
    out = {}
    for code, (system, subsystem, severity, drivable, en, ar, sigs, causes) in E.items():
        out[code] = {
            "system": system, "subsystem": subsystem, "en": en, "ar": ar,
            "severity": severity, "drivable": drivable,
            "related_signals": sigs, "common_causes": causes,
        }
    return out


def main(argv: list[str]) -> int:
    write = "--write" in argv
    kb = json.loads(KB.read_text(encoding="utf-8"))
    codes = kb["codes"]
    gen = build()
    new = {k: v for k, v in gen.items() if k not in codes}
    print(f"authored {len(gen)} discrete codes; {len(new)} are new")
    print("new:", ", ".join(sorted(new)))
    if not write:
        print("\n(dry run — pass --write to merge)")
        return 0
    codes.update(new)
    kb["codes"] = {k: codes[k] for k in sorted(codes)}
    kb["kb_version"] = "2026.10.2"
    KB.write_text(json.dumps(kb, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print(f"\nwrote {KB} — total codes now {len(kb['codes'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
